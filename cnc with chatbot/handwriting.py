DEFAULT_CHAR = [(0, 20), (10, 0), (0, -20), (-10, 0)] # A box for unknown chars

def text_to_actions(text):
    """
    Converts a string of text into a list of actions for the plotter.
    Actions can be ('PEN_UP'), ('PEN_DOWN'), or ('MOVE', dx, dy).
    """
    actions = []
    
    for char in text.upper():
        char_strokes = FONT.get(char, DEFAULT_CHAR)
        
        actions.append(('PEN_UP',))

        if char == ' ':
            actions.append(('MOVE', 15, 0))
            continue

        # Move to the start of the first stroke without drawing
        first_stroke = char_strokes[0]
        actions.append(('MOVE', first_stroke[0], first_stroke[1]))

        actions.append(('PEN_DOWN',))

        # Draw the rest of the character
        for i in range(1, len(char_strokes)):
            dx, dy = char_strokes[i]
            actions.append(('MOVE', dx, dy))
        
        actions.append(('PEN_UP',))
        
        # Advance to the next character position (fixed width)
        actions.append(('MOVE', 15, 0))

    return actions
